"""Generate plain-text and CSV summaries for preliminary results."""
from __future__ import annotations
import csv
import io


def _fmt(value):
    if value is None:
        return "Not calculated"
    if isinstance(value, float):
        return f"{value:.6g}"
    return str(value)


def result_to_text(result: dict, process_inputs: dict, geometry: dict) -> str:
    lines = [
        "EVAPORATOR DESIGN / RATING — PRELIMINARY STARTER REPORT",
        "=" * 58,
        f"Mode: {result.get('mode', 'Unknown')}",
        f"Exchanger: {result.get('exchanger', 'Unknown')}",
        f"Status: {result.get('status', 'Unknown')}",
        "",
        "IMPORTANT: This is a software scaffold using simplified illustrative calculations.",
        "Do not use for procurement, operation, safety sign-off, or final equipment design.",
        "",
        "PROCESS INPUTS",
    ]
    lines += [f"{key}: {_fmt(value)}" for key, value in process_inputs.items()]
    lines += ["", "GEOMETRY INPUTS"]
    lines += [f"{key}: {_fmt(value)}" for key, value in geometry.items()]
    lines += ["", "RESULTS"]
    skip = {"thermal", "warnings", "errors", "calculation_trace", "model_notes", "preliminary_checks", "process_dp", "hot_dp"}
    for key, value in result.items():
        if key not in skip and not isinstance(value, (dict, list)):
            lines.append(f"{key}: {_fmt(value)}")
    if "thermal" in result:
        lines += ["", "THERMAL BASIS"]
        lines += [f"{k}: {_fmt(v)}" for k, v in result["thermal"].items() if k != "warnings"]
    for title, key in [("PROCESS-SIDE PRESSURE-DROP PROXY", "process_dp"), ("HEATING-SIDE PRESSURE-DROP PROXY", "hot_dp")]:
        lines += ["", title]
        lines += [f"{k}: {_fmt(v)}" for k, v in (result.get(key) or {}).items()]
    lines += ["", "WARNINGS / LIMITATIONS"]
    all_warnings = list(result.get("warnings") or []) + list(result.get("model_notes") or [])
    if all_warnings:
        lines += [f"- {warning}" for warning in dict.fromkeys(all_warnings)]
    else:
        lines.append("- No warnings were generated by the current placeholder checks.")
    lines += ["", "CALCULATION TRACE"]
    lines += [f"- {step}" for step in result.get("calculation_trace", [])]
    return "\n".join(lines)


def result_to_csv(result: dict) -> str:
    flat = {}
    for key, value in result.items():
        if isinstance(value, dict):
            for subkey, subvalue in value.items():
                if isinstance(subvalue, (str, int, float, bool)) or subvalue is None:
                    flat[f"{key}.{subkey}"] = subvalue
        elif isinstance(value, list):
            flat[key] = " | ".join(map(str, value))
        else:
            flat[key] = value
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["parameter", "value"])
    for key, value in flat.items():
        writer.writerow([key, value])
    return buf.getvalue()
